#!/usr/bin/env bash
# cline-rotate — supervisor for the Cline CLI.
# Automatically switches free models on "Daily free model limit reached",
# and switches to another account when all models in the rotation are exhausted.
#
# Usage:
#   ./cline-rotate.sh "prompt"            # act mode, auto-approve
#   ./cline-rotate.sh -p "prompt"         # plan mode
#   ./cline-rotate.sh --session <id> "prompt"
#   ./cline-rotate.sh                     # interactive: probe, then open a REPL
#   CLINE_ACCOUNTS_DIR=/path ./cline-rotate.sh "prompt"
#   CLINE_MODELS="a b c" ./cline-rotate.sh "prompt"
#   CLINE_EXTRA_ARGS="--timeout 600" ./cline-rotate.sh "prompt"
#
# Env:
#   CLINE_ACCOUNTS_DIR  accounts root        (default: ~/.cline/accounts)
#   CLINE_MODELS        space-separated model ids, first = preferred
#   CLINE_BIN           cline binary         (default: cline from PATH)
#   CLINE_RETRIES       --retries value      (default: 12)
#   CLINE_RUN_TIMEOUT   seconds per real run (default: 900)
#   CLINE_STALL_WINDOW  silence before the call is killed (default: 120)
#   CLINE_STALL_CHECK   heartbeat poll interval      (default: 30)
#   CLINE_PROBE_TIMEOUT seconds per probe    (default: 45)
#   CLINE_MAX_ACCOUNT_ROUNDS account switch loop guard (default: number of accounts)
#   CLINE_LOG_DIR       where to write cline-rotate.log (default: $CLINE_ACCOUNTS_DIR/../logs)
#   AI_ROTATE_DIR       shared model-health store     (default: ~/.ai-rotate)
#   CLINE_NO_STATS=1    ignore the shared store, keep the file order
#   CLINE_SAVE_MODEL=1  persist the winning model into providers.json (default: off;
#                      the run already pins -m explicitly, so off avoids clobbering
#                      the per-account model you set by hand)

set -uo pipefail

# ── Shared model-health store (see _shared/model-stats.py) ─────────────────────
# Every rotate skill records its probe results into one file, so a model proven
# dead by cline is skipped by OpenCode/FreeBuff too, and rotation order follows
# measured stability instead of the order in cline-models-free.txt.
SKILLS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." >/dev/null 2>&1 && pwd)"
STATS="$SKILLS_DIR/_shared/model-stats.py"
STATS_SKILL="cline"
NO_STATS="${CLINE_NO_STATS:-0}"
[[ -f "$STATS" && "$NO_STATS" != "1" ]] || STATS=""

# ── Free-model rotation ───────────────────────────────────────────────────────
# The model list is generated by cline_Models_Free_Make.sh from the cline binary itself and
# ordered by your priority in models_4_rotattion.txt. This fallback is used only
# when those files are missing.
DEFAULT_MODELS=(
	"cline-free/deepseek-v4.1-flash"
	"cline-free/muse-spark-1.3-contributor"
	"z-ai/glm-5.3-flash"
	"cline-free/solar-pro4"
	"poolside/laguna-s-2.1:free"
)

ACCOUNTS_DIR="${CLINE_ACCOUNTS_DIR:-$HOME/.cline/accounts}"
CLINE_BIN="${CLINE_BIN:-cline}"
CLINE_RETRIES="${CLINE_RETRIES:-12}"
# A provider that stops answering must cost one model, not the whole step.
# cline has its own --timeout, so the bound lives inside the binary instead of
# an external watchdog: killing child processes from a subshell is not allowed
# on every host, and a rotate script that needs `kill` to make progress is a
# rotate script that silently hangs where `kill` is denied.
RUN_TIMEOUT="${CLINE_RUN_TIMEOUT:-900}"
# Heartbeat: a provider that hangs mid-stream gives no error and no output.
# Waiting for the supervisor's 30-minute step timeout wastes the whole budget,
# so the run is watched every STALL_CHECK seconds: if the session files have
# not grown for STALL_WINDOW seconds, the model is mute and the call is killed.
STALL_WINDOW="${CLINE_STALL_WINDOW:-120}"
STALL_CHECK="${CLINE_STALL_CHECK:-30}"
PROBE_TIMEOUT="${CLINE_PROBE_TIMEOUT:-45}"
LOG_DIR="${CLINE_LOG_DIR:-$ACCOUNTS_DIR/../logs}"
mkdir -p "$LOG_DIR" 2>/dev/null || true
ROTATE_LOG="$LOG_DIR/cline-rotate.log"

# Resolve the skill directory: works for direct invocation, PATH invocation,
# and symlinked wrappers (SKILL_DIR/cline-rotate.sh -> skill/cline/cline-rotate.sh).
SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
if [[ -L "${BASH_SOURCE[0]}" ]]; then
	SKILL_DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" >/dev/null 2>&1 && pwd)"
fi
MODELS_FILE="$SKILL_DIR/cline-models-free.txt"

clog() {
	printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" | tee -a "$ROTATE_LOG" 2>/dev/null ||
		printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"
}

# Read the free-model catalogue generated by cline_Models_Free_Make.sh. The ids in that file
# are exactly what `cline -m` accepts, so no name resolution is needed.
read_models() {
	while IFS= read -r line; do
		[[ -z "$line" || "$line" == \#* ]] && continue
		printf '%s\n' "${line%%$'\t'*}"
	done <"$MODELS_FILE"
}

if [[ -n "${CLINE_MODELS:-}" ]]; then
	# shellcheck disable=SC2206
	MODELS=(${CLINE_MODELS})
elif [[ -f "$MODELS_FILE" ]]; then
	# shellcheck disable=SC2206
	MODELS=($(read_models))
	if [[ ${#MODELS[@]} -eq 0 ]]; then
		clog "warning: $MODELS_FILE is empty, using built-in list"
		MODELS=("${DEFAULT_MODELS[@]}")
	fi
else
	MODELS=("${DEFAULT_MODELS[@]}")
	clog "warning: $MODELS_FILE missing, using built-in list"
	clog "         run $SKILL_DIR/cline_Models_Free_Make.sh to generate it"
fi

# An account is only usable if its configured model participates in the
# rotation. A stale/mismatched model (e.g. a paid one whose key was revoked)
# must not be trusted: the probe below pins a rotation model explicitly.
in_rotation() {
	local m="$1"
	for r in "${MODELS[@]}"; do [[ "$r" == "$m" ]] && return 0; done
	return 1
}

# ── Collect accounts ──────────────────────────────────────────────────────────
# An account is skipped when it has no providers.json at all, or when the model
# configured for it is not part of the rotation (stale/paid/revoked model).
ACCOUNTS=()
if [[ -d "$ACCOUNTS_DIR" ]]; then
	while IFS= read -r dir; do
		[[ -z "$dir" ]] && continue
		p="$ACCOUNTS_DIR/$dir/settings/providers.json"
		[[ -f "$p" ]] || continue
		configured="$(python3 -c "
import json
try:
    print(json.load(open('$p'))['providers']['cline']['settings'].get('model') or '')
except Exception:
    print('')
" 2>/dev/null)"
		if [[ -z "$configured" ]]; then
			clog "skip account [$dir]: no model configured in providers.json"
			continue
		fi
		if ! in_rotation "$configured"; then
			clog "skip account [$dir]: model '$configured' is outside the rotation"
			continue
		fi
		ACCOUNTS+=("$ACCOUNTS_DIR/$dir")
	done < <(ls -1 "$ACCOUNTS_DIR" 2>/dev/null)
fi

if [[ ${#ACCOUNTS[@]} -eq 0 ]]; then
	echo "cline-rotate: no accounts found under $ACCOUNTS_DIR" >&2
	echo "hint: CLINE_ACCOUNTS_DIR=/path/to/accounts $0 ..." >&2
	exit 3
fi

MAX_ACCOUNT_ROUNDS="${CLINE_MAX_ACCOUNT_ROUNDS:-${#ACCOUNTS[@]}}"

# ── Parse CLI args ────────────────────────────────────────────────────────────
MODE="act"
SESSION_ID=""
PROMPT=""
EXTRA_ARGS=()
while [[ $# -gt 0 ]]; do
	case "$1" in
	-p | --plan)
		MODE="plan"
		shift
		;;
	--session)
		SESSION_ID="${2:-}"
		shift 2
		;;
	--session=*)
		SESSION_ID="${1#*=}"
		shift
		;;
	-h | --help)
		sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	--)
		shift
		while [[ $# -gt 0 ]]; do
			PROMPT="${PROMPT:+$PROMPT }$1"
			shift
		done
		;;
	-*)
		EXTRA_ARGS+=("$1")
		shift
		;;
	*)
		PROMPT="${PROMPT:+$PROMPT }$1"
		shift
		;;
	esac
done
[[ -n "${CLINE_EXTRA_ARGS:-}" ]] && EXTRA_ARGS+=($CLINE_EXTRA_ARGS)

if [[ -z "$PROMPT" && -z "$SESSION_ID" ]]; then
	# No prompt = interactive REPL. We still probe first so the session opens on
	# a model that is not already over its daily cap.
	INTERACTIVE=1
else
	INTERACTIVE=0
fi

# ── Model limit detection ─────────────────────────────────────────────────────
# In non-interactive mode the CLI exits 1 AND prints the limit banner, so the
# exit code cannot be trusted — we match on the message text instead.
# Returns 0 (true)  => free-model limit hit, rotate to another model.
# Returns 1 (false) => genuine failure / success, do not burn the rotation.
is_model_limit() {
	local out="$1"
	[[ "$out" == *"Daily free model limit reached"* ]] ||
		[[ "$out" == *"today's free usage limit"* ]] ||
		[[ "$out" == *"INFERENCE_CAP_ERROR"* ]] ||
		[[ "$out" == *"Free model promotion ended"* ]]
}

# The model stopped answering: cline's own --timeout fired, or the provider
# closed the stream. This is a model-level failure — the credential answered a
# probe a minute ago — so the next model on the same account is the right move.
is_timeout() {
	local out="$1"
	[[ "$out" == *"timed out"* ]] || [[ "$out" == *"timeout"* ]] ||
		[[ "$out" == *"Timeout"* ]] || [[ "$out" == *"ETIMEDOUT"* ]]
}

# The account, not the model, is out: no credit, revoked key, hard quota.
# Rotating the model inside this account cannot help — only another --data-dir.
# Returns 0 (true) => switch account.
is_account_failure() {
	local out="$1"
	[[ "$out" == *"402"* ]] ||
		[[ "$out" == *"credit"* ]] ||
		[[ "$out" == *"Credit"* ]] ||
		[[ "$out" == *"wallet"* ]] ||
		[[ "$out" == *"401"* ]] ||
		[[ "$out" == *"403"* ]] ||
		[[ "$out" == *"Unauthorized"* ]] ||
		[[ "$out" == *"Invalid API key"* ]] ||
		[[ "$out" == *"key has expired"* ]] ||
		[[ "$out" == *"quota"* ]] ||
		[[ "$out" == *"Quota"* ]]
}

# ── Rotation order ────────────────────────────────────────────────────────────
# Reads candidate ids on stdin, prints them best-first: healthy ones by measured
# stability, then cooling-down, then unknown. Models in `auth_error` are dropped
# (a bad key needs a human, not a retry). FAMILY_OF lifts the siblings of the
# model that just died to the front, so a dead deepseek/* falls over to another
# deepseek/* instead of an unrelated model. Falls back to the input order when
# the store is off or unreadable.
FAMILY_OF=""
rotation_order() {
	local -a ids=()
	local l
	while IFS= read -r l; do [[ -n "$l" ]] && ids+=("$l"); done
	[[ ${#ids[@]} -eq 0 ]] && return 0
	if [[ -z "$STATS" ]]; then
		printf '%s\n' "${ids[@]}"
		return 0
	fi
	local -a args=("$STATS_SKILL" --models "${ids[@]}")
	[[ -n "$FAMILY_OF" ]] && args+=(--family-of "$FAMILY_OF")
	local out errf
	errf="$(mktemp)"
	out="$(python3 "$STATS" order "${args[@]}" 2>"$errf")"
	# The store explains itself on stderr ("family hop: x -> deepseek"). Send it
	# straight to the log — never to stdout, which the caller captures.
	[[ -s "$errf" ]] && clog "$(cat "$errf")" >>"$ROTATE_LOG" 2>&1
	rm -f "$errf"
	if [[ -n "$out" ]]; then
		printf '%s\n' "$out"
	else
		printf '%s\n' "${ids[@]}"
	fi
}

# ── Record a probe result in the shared store ─────────────────────────────────
# $1=model $2=verdict(ok|fail|auth|limit) $3=latency_ms $4=error text
# Newest file a worker writes while it is thinking: its session log. If this
# file's mtime stops moving, the model is not producing anything.
newest_session_file() {
	local dir="$1"
	ls -t "$dir"/sessions/*/*.messages.json 2>/dev/null | head -1
}

mtime_of() { stat -f %m "$1" 2>/dev/null || stat -c %Y "$1" 2>/dev/null || echo 0; }

# Watch one run: every STALL_CHECK seconds take the newest sign of life —
# the session file cline writes while it thinks, or the captured output.
# Nothing moved for STALL_WINDOW -> the model is mute, kill the call.
# The output file counts on purpose: a worker that never even started a
# session (hung before the first token) must also be caught.
stall_guard() {
	local pid="$1" sess="$2" out="$3"
	local now m mo f tick=0
	while kill -0 "$pid" 2>/dev/null; do
		# Sleep in one-second slices: a guard blocked in a single long sleep
		# cannot be stopped when the run ends normally, and every normal run
		# then pays STALL_CHECK seconds before the script can continue.
		sleep 1
		tick=$((tick + 1))
		(( tick < STALL_CHECK )) && continue
		tick=0
		m=0
		f="$(newest_session_file "$sess")"
		[[ -n "$f" ]] && m="$(mtime_of "$f")"
		[[ -f "$out" ]] && { mo="$(mtime_of "$out")"; (( mo > m )) && m="$mo"; }
		now="$(date +%s)"
		if (( now - m >= STALL_WINDOW )); then
			clog "  stall  ${STALL_WINDOW}s без движения сессии ($f) -> kill $pid"
			kill -TERM "$pid" 2>/dev/null
			sleep 5
			kill -9 "$pid" 2>/dev/null
			return 0
		fi
	done
}

stats_record() {
	[[ -z "$STATS" ]] && return 0
	python3 "$STATS" record "$STATS_SKILL" "$1" "$2" "${3:-}" "${4:-}" 2>&1 |
		while IFS= read -r l; do clog "$l"; done
}

# ── Probe one model: quick one-shot run to see if it answers ──────────────────
# Exit codes: 0 = model alive, 1 = model limit reached, 2 = account-level error.
probe_model() {
	local account_dir="$1" model="$2"
	local email
	email="$(python3 -c "
import json,sys
try:
    d=json.load(open('$account_dir/settings/providers.json'))
    print(d['providers']['cline']['settings']['auth']['metadata']['userInfo'].get('email','?'))
except Exception:
    print('?')
" 2>/dev/null)"

	local probe_prompt='answer with the single word: ok'
	local out rc elapsed
	local t0 t1
	t0="$(date +%s)"
	out="$("$CLINE_BIN" --auto-approve false --retries 1 --timeout "$PROBE_TIMEOUT" \
		--data-dir "$account_dir" -m "$model" "$probe_prompt" 2>&1)"
	rc=$?
	t1="$(date +%s)"
	((elapsed = (t1 - t0) * 1000))

	if is_model_limit "$out"; then
		clog "  probe  model=$model account=$email -> LIMIT REACHED"
		stats_record "$model" limit "$elapsed" "daily free model limit"
		return 1
	fi
	if [[ $rc -ne 0 ]]; then
		clog "  probe  model=$model account=$email -> ERROR rc=$rc"
		clog "         account-level failure, skipping whole account"
		# A non-limit error is an account/credential problem, not a model one.
		stats_record "$model" auth "$elapsed" "$(printf '%s' "$out" | tail -1)"
		return 2
	fi
	clog "  probe  model=$model account=$email -> OK (${elapsed}ms)"
	stats_record "$model" ok "$elapsed"
	return 0
}

# ── Persist the winning model as the account default ──────────────────────────
save_model() {
	local account_dir="$1" model="$2"
	python3 - "$account_dir/settings/providers.json" "$model" <<'PY' 2>/dev/null || true
import json, sys
path, model = sys.argv[1], sys.argv[2]
with open(path) as f:
    d = json.load(f)
s = d["providers"]["cline"]["settings"]
if s.get("model") == model:
    sys.exit(0)
s["model"] = model
d["providers"]["cline"]["updatedAt"] = __import__("datetime").datetime.utcnow().isoformat() + "Z"
with open(path, "w") as f:
    json.dump(d, f, indent=2)
PY
	clog "  saved  model=$model as account default"
}

# ── Main ──────────────────────────────────────────────────────────────────────
ACCOUNT_IDX=0
ACCOUNT_DEAD=""
DEAD_MODELS=() # models confirmed dead in the current account
GLOBAL_DEAD=() # "model|account" pairs dead in this invocation
TOTAL_ATTEMPTS=0
((TOTAL_ATTEMPTS_MAX = ${#ACCOUNTS[@]} * ${#MODELS[@]} + 5))

while true; do
	((TOTAL_ATTEMPTS += 1))
	if ((TOTAL_ATTEMPTS > TOTAL_ATTEMPTS_MAX)); then
		clog "ABORT: loop guard triggered ($TOTAL_ATTEMPTS_MAX attempts) — possible infinite loop"
		echo "cline-rotate: aborted, loop guard" >&2
		exit 4
	fi

	ACCOUNT_DIR="${ACCOUNTS[$ACCOUNT_IDX]}"
	ACCOUNT_NAME="$(basename "$ACCOUNT_DIR")"
	clog "== account [$ACCOUNT_NAME] (round $TOTAL_ATTEMPTS)"

	model=""
	remaining=("${MODELS[@]}")
	FAMILY_OF=""
	while [[ ${#remaining[@]} -gt 0 ]]; do
		# Re-ordered on every pass: after a limit hit, the dead model's family
		# leads the remainder (family-preserving failover).
		next="$(printf '%s\n' "${remaining[@]}" | rotation_order | head -1)"
		[[ -n "$next" ]] || break
		rest=()
		for m in "${remaining[@]}"; do [[ "$m" == "$next" ]] || rest+=("$m"); done
		remaining=("${rest[@]}")

		skip=0
		for d in "${DEAD_MODELS[@]:-}"; do [[ "$d" == "$next" ]] && skip=1 && break; done
		for g in "${GLOBAL_DEAD[@]:-}"; do [[ "$g" == "$next|$ACCOUNT_NAME" ]] && skip=1 && break; done
		((skip)) && continue

		probe_model "$ACCOUNT_DIR" "$next"
		prc=$?
		case $prc in
		0)
			model="$next"
			break
			;;
		1)
			DEAD_MODELS+=("$next")
			GLOBAL_DEAD+=("$next|$ACCOUNT_NAME")
			FAMILY_OF="$next"
			;;
		2)
			ACCOUNT_DEAD=1
			break
			;; # auth/broken account: skip it entirely
		esac
	done
	FAMILY_OF=""

	# ── Account dead or all its models exhausted: rotate to the next one ──────
	if [[ -z "$model" ]]; then
		if [[ -n "$ACCOUNT_DEAD" ]]; then
			clog "  account [$ACCOUNT_NAME] unusable (auth/error), skipping"
			ACCOUNT_DEAD=""
		else
			clog "  all ${#MODELS[@]} models exhausted on [$ACCOUNT_NAME]"
		fi
		DEAD_MODELS=()
		((ACCOUNT_IDX += 1))
		if ((ACCOUNT_IDX >= ${#ACCOUNTS[@]})); then
			clog "  end of account list — re-probing from the first account"
			ACCOUNT_IDX=0
			GLOBAL_DEAD=()
			sleep 2
		fi
		((MAX_ACCOUNT_ROUNDS -= 1))
		if ((MAX_ACCOUNT_ROUNDS <= 0)); then
			clog "ABORT: all accounts exhausted (tried ${#ACCOUNTS[@]} account(s), ${#MODELS[@]} model(s))"
			echo "cline-rotate: all accounts exhausted" >&2
			exit 5
		fi
		continue
	fi

	# ── Run the real task on the working model ─────────────────────────────────
	# save_model persists the winning model back into providers.json. It is OFF
	# by default: the script always passes -m explicitly, so persisting only
	# risks clobbering the per-account model the user deliberately configured.
	# Opt in with CLINE_SAVE_MODEL=1 if you want a "sticky winner" next time.
	[[ "${CLINE_SAVE_MODEL:-0}" == "1" ]] && save_model "$ACCOUNT_DIR" "$model"

	local_args=(--auto-approve true --retries "$CLINE_RETRIES" --data-dir "$ACCOUNT_DIR"
		--timeout "$RUN_TIMEOUT")
	[[ "$MODE" == "plan" ]] && local_args+=(-p)
	[[ -n "$SESSION_ID" ]] && local_args+=(--id "$SESSION_ID")
	[[ ${#EXTRA_ARGS[@]} -gt 0 ]] && local_args+=("${EXTRA_ARGS[@]}")
	local_args+=(-m "$model")

	# Interactive: hand the terminal over to cline on a live model.
	if [[ "$INTERACTIVE" == "1" ]]; then
		clog "  shell  model=$model account=$ACCOUNT_NAME (interactive)"
		exec "$CLINE_BIN" "${local_args[@]}"
	fi

	clog "  run    model=$model account=$ACCOUNT_NAME timeout=${RUN_TIMEOUT}s stall=${STALL_WINDOW}s prompt=${PROMPT:0:60}..."
	RUN_OUT_FILE="$(mktemp "${TMPDIR:-/tmp}/cline-run.XXXXXX")" || RUN_OUT_FILE=/dev/null
	"$CLINE_BIN" "${local_args[@]}" "$PROMPT" >"$RUN_OUT_FILE" 2>&1 &
	RUN_PID=$!
	stall_guard "$RUN_PID" "$ACCOUNT_DIR" "$RUN_OUT_FILE" &
	GUARD_PID=$!
	wait "$RUN_PID"
	RC=$?
	kill "$GUARD_PID" 2>/dev/null
	wait "$GUARD_PID" 2>/dev/null
	OUT="$(cat "$RUN_OUT_FILE" 2>/dev/null)"
	rm -f "$RUN_OUT_FILE"

	if [[ $RC -eq 143 || $RC -eq 137 ]]; then
		# The guard killed it after STALL_WINDOW seconds of silence. Same
		# verdict as a provider timeout: the model is mute, the account is not.
		clog "  stall  model=$model silent ${STALL_WINDOW}s -> next model, same account"
		stats_record "$model" fail "" "stalled ${STALL_WINDOW}s"
		DEAD_MODELS+=("$model")
		GLOBAL_DEAD+=("$model|$ACCOUNT_NAME")
		continue
	fi

	if is_timeout "$OUT"; then
		# The provider stopped answering: this model is mute, the account is
		# not. Drop the model and keep the account.
		clog "  timeout model=$model -> next model, same account"
		stats_record "$model" fail "" "run timeout ${RUN_TIMEOUT}s"
		DEAD_MODELS+=("$model")
		GLOBAL_DEAD+=("$model|$ACCOUNT_NAME")
		continue
	fi

	if is_model_limit "$OUT"; then
		clog "  limit hit mid-run on model=$model -> rotate"
		stats_record "$model" limit "" "daily free model limit (mid-run)"
		DEAD_MODELS+=("$model")
		GLOBAL_DEAD+=("$model|$ACCOUNT_NAME")
		continue
	fi

	printf '%s\n' "$OUT"
	if [[ $RC -ne 0 ]]; then
		clog "  done   rc=$RC model=$model account=$ACCOUNT_NAME"
		stats_record "$model" fail "" "run rc=$RC"

		# The run failed. Do NOT end the whole invocation here: this account is
		# one of several --data-dir trees, and the next one may well work.
		# Switch account, keep the prompt, try again — bounded by
		# MAX_ACCOUNT_ROUNDS so five dead accounts still end in a clear exit.
		((MAX_ACCOUNT_ROUNDS -= 1))
		if ((MAX_ACCOUNT_ROUNDS <= 0)); then
			clog "ABORT: all ${#ACCOUNTS[@]} account(s) tried, none finished the task"
			echo "cline-rotate: all accounts exhausted" >&2
			exit 5
		fi
		if is_account_failure "$OUT"; then
			clog "  account [$ACCOUNT_NAME] is out (credit/key/quota) -> next --data-dir"
		else
			clog "  run failed on [$ACCOUNT_NAME] -> next --data-dir"
		fi
		# A new account starts with a clean model slate: the previous account's
		# dead models say nothing about this one.
		GLOBAL_DEAD+=("$model|$ACCOUNT_NAME")
		DEAD_MODELS=()
		ACCOUNT_IDX=$(((ACCOUNT_IDX + 1) % ${#ACCOUNTS[@]}))
		continue
	fi

	clog "  done   rc=0 model=$model account=$ACCOUNT_NAME"
	stats_record "$model" ok ""
	exit 0
done
